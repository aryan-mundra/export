// Generates regliss-mock.sql. Deterministic: same output every run.
//   node db/oracle/generate-regliss-mock.js db/oracle/regliss-mock.sql
const fs = require("fs");
const out = process.argv[2] || require("path").join(__dirname, "regliss-mock.sql");

// Awkward values that file writers must handle: commas, quotes, apostrophes, & and <,
// non-ASCII letters, leading/trailing spaces and a line break. "&" is written as CHR(38)
// so SQL*Plus does not treat it as a substitution variable.
const AMP = { sql: "'Smith ' || CHR(38) || ' Sons <Holdings>'" };
const QUOTES = "O'Brien, Sean \"Jr\"";
const UNICODE = "Zoë Ünal – Ελένη";
const SPACES = "  Padded Name  ";
const SPECIAL_NAMES = { 14: AMP, 60: AMP, 20: QUOTES, 54: QUOTES, 34: UNICODE, 80: UNICODE, 40: SPACES, 94: SPACES };
const SPECIAL_STREETS = { 20: { sql: "'Line one' || CHR(10) || 'Line two, \"B\"'" }, 54: { sql: "'Line one' || CHR(10) || 'Line two, \"B\"'" }, 14: { sql: "'5 Rue ' || CHR(38) || ' Co'" } };

const VERSIONS = [
    { id: 42, code: "SANCTIONS", name: "Sanctions", asOf: "2026-11-18", visible: 1 },
    { id: 43, code: "WORLDCHECK", name: "World-Check", asOf: "2026-11-01", visible: 1 },
    { id: 44, code: "PFA", name: "PFA", asOf: "2026-10-15", visible: 1 },
    { id: 77, code: "SANCTIONS", name: "Sanctions", asOf: "2026-11-18", visible: 0 }
];
const PER_VERSION = 100;
const NAMES = ["Amina Diallo", "Hugo Martin", "Priya Nair", "Elena Rossi", "Noah Keller", "Sofia Alvarez",
    "James Okonkwo", "Mei Chen", "Lars Andersen", "Fatima Haddad", "Owen Blake", "Chloe Dubois",
    "Ravi Kapoor", "Nora Berg", "Hassan Ali", "Emma Clarke", "Luca Bianchi", "Yuki Tanaka", "Ines Moreau", "Daniel Kruger"];
const COUNTRIES = ["FR", "US", "GB", "DE", "IN", "SG", "AE", "CH", "JP", "BR"];
const CITIES = ["Paris", "New York", "London", "Berlin", "Mumbai", "Singapore", "Dubai", "Zurich", "Tokyo", "Sao Paulo"];
const STREETS = ["Rue de Rivoli", "Fifth Avenue", "Baker Street", "Unter den Linden", "Marine Drive"];
const ACTIONS = ["ADD", "MODIFY", "DELETE"];
const RISKS = ["LOW", "MEDIUM", "HIGH"];
const LINES = ["CIB", "Retail", "Compliance", "Financial Security"];
const REGIONS = ["EMEA", "APAC", "Europe", "Americas", "Global"];
const PARTY_TYPES = ["INDIVIDUAL", "ENTITY", "VESSEL"];
const PROGRAMS = ["EU-CFSP", "OFAC-SDN", "UN-1267", "UK-HMT"];
const ID_TYPES = ["PASSPORT", "NATIONAL_ID", "TAX_ID"];

const q = v => v === null ? "NULL" : typeof v === "number" ? String(v) : v.sql ? v.sql : "'" + String(v).replace(/'/g, "''") + "'";
const d = iso => iso === null ? "NULL" : `DATE '${iso}'`;
const pad = n => String(n).padStart(2, "0");
const minusDays = (iso, days) => {
    const t = new Date(iso + "T00:00:00Z");
    t.setUTCDate(t.getUTCDate() - days);
    return `${t.getUTCFullYear()}-${pad(t.getUTCMonth() + 1)}-${pad(t.getUTCDate())}`;
};
const ins = (table, cols, vals) => `INSERT INTO ${table} (${cols.join(", ")}) VALUES (${vals.join(", ")});`;

const L = [];
const p = s => L.push(s);

p(`-- =============================================================================
-- REGLISS mock database for the Export module (Oracle)
--
-- Creates and fills the tables the Export module READS:
--   VER_VERSION           certified list versions (the catalog the Export page offers)
--   VER_VERSION_MEMBER    list records in each version (what goes into the files)
--   GS_PARTY, GS_ADDRESS, GS_IDENTIFIER, GS_SANCTION_PROGRAM
--                         golden-source tables, matched to a list entry on BNP_ID
--   GS_COUNTRY_RISK       risk of each party's country, one row per BNP_ID
--   GS_LOAD_LOG           a gs_ table with no BNP_ID column (shown but locked)
--   REF_COUNTRY           not a gs_ table, so the Format Templates page must not show it
--
-- The module's own VER_EXPORT_* tables are NOT created here: the application creates
-- them on first start (spring.jpa.hibernate.ddl-auto=update in the oracle profile).
--
-- This is a mock schema made for testing. Check column names and types against the
-- real REGLISS schema before relying on it.
--
-- Data: versions 42, 43, 44 (visible) and 77 (hidden), ${PER_VERSION} records each.
--       Some names and streets hold commas, quotes, ampersands, <, non-ASCII letters, padding
--       and a line break, to prove the CSV and XML writers escape them correctly.
--       Every 29th record has no NAME and every 41st has no COUNTRY, so the quality
--       check has something to quarantine. Every 13th record has no GS_ADDRESS row.
--
-- Run as the schema owner, for example in SQL*Plus or SQLcl:
--   @regliss-mock.sql
-- Safe to run again: it drops and recreates its own tables (DROP TABLE IF EXISTS
-- needs Oracle 23ai; on 19c remove "IF EXISTS" and ignore "table does not exist" errors).
-- Generated by generate-regliss-mock.js: edit that and run it again, not this file.
-- =============================================================================
`);

for (const t of ["GS_SANCTION_PROGRAM", "GS_IDENTIFIER", "GS_ADDRESS", "GS_PARTY", "GS_LOAD_LOG", "GS_COUNTRY_RISK", "REF_COUNTRY", "VER_VERSION_MEMBER", "VER_VERSION"]) {
    p(`DROP TABLE IF EXISTS ${t};`);
}
p("");
p(`-- Certified versions. Column names match the application's mapping of this table.
CREATE TABLE VER_VERSION (
    ID               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    VERSION_ID       NUMBER(19)    NOT NULL,
    LIST_CODE        VARCHAR2(255) NOT NULL,
    LIST_NAME        VARCHAR2(255) NOT NULL,
    CONTENT_AS_OF    DATE,
    STATUS           VARCHAR2(255) NOT NULL,
    OPERATOR_VISIBLE NUMBER(1)     DEFAULT 1 NOT NULL,
    CONSTRAINT UQ_VER_VERSION_VERSION_ID UNIQUE (VERSION_ID)
);

-- One row per list record in a certified version.
CREATE TABLE VER_VERSION_MEMBER (
    VERSION_ID     NUMBER(19)    NOT NULL,
    RECORD_ID      NUMBER(19)    NOT NULL,
    BNP_ID         VARCHAR2(20)  NOT NULL,
    NAME           VARCHAR2(200),
    COUNTRY        VARCHAR2(2),
    RECORD_DATE    DATE,
    ACTION         VARCHAR2(10),
    RISK_RATING    VARCHAR2(10),
    BUSINESS_LINE  VARCHAR2(50),
    REGION         VARCHAR2(50),
    CHANGED_ON     DATE,
    ON_SANCTIONS   NUMBER(1) DEFAULT 0 NOT NULL,
    ON_WORLDCHECK  NUMBER(1) DEFAULT 0 NOT NULL,
    ON_PFA         NUMBER(1) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_VER_VERSION_MEMBER PRIMARY KEY (VERSION_ID, RECORD_ID)
);

CREATE TABLE GS_PARTY (
    BNP_ID      VARCHAR2(20) PRIMARY KEY,
    FULL_NAME   VARCHAR2(200),
    PARTY_TYPE  VARCHAR2(30),
    NATIONALITY VARCHAR2(2),
    BIRTH_PLACE VARCHAR2(100),
    RISK_SCORE  NUMBER(3)
);

CREATE TABLE GS_ADDRESS (
    BNP_ID       VARCHAR2(20) NOT NULL,
    STREET       VARCHAR2(200),
    CITY         VARCHAR2(100),
    POSTAL_CODE  VARCHAR2(20),
    COUNTRY_CODE VARCHAR2(2)
);
CREATE INDEX IX_GS_ADDRESS_RECORD ON GS_ADDRESS (BNP_ID);

CREATE TABLE GS_IDENTIFIER (
    BNP_ID    VARCHAR2(20) NOT NULL,
    ID_TYPE   VARCHAR2(30),
    ID_VALUE  VARCHAR2(60),
    ISSUED_BY VARCHAR2(2)
);
CREATE INDEX IX_GS_IDENTIFIER_RECORD ON GS_IDENTIFIER (BNP_ID);

CREATE TABLE GS_SANCTION_PROGRAM (
    BNP_ID       VARCHAR2(20) NOT NULL,
    PROGRAM_CODE VARCHAR2(30),
    LISTED_ON    DATE
);
CREATE INDEX IX_GS_SANCTION_PROGRAM_RECORD ON GS_SANCTION_PROGRAM (BNP_ID);

-- No BNP_ID column: shown on the Format Templates page but locked, because its rows
-- cannot be matched to list entries.
CREATE TABLE GS_LOAD_LOG (
    LOAD_REF  VARCHAR2(40),
    LOADED_AT TIMESTAMP,
    ROW_COUNT NUMBER(10)
);

-- Risk of the country each party is linked to, one row per BNP_ID.
CREATE TABLE GS_COUNTRY_RISK (
    BNP_ID            VARCHAR2(20) NOT NULL,
    COUNTRY_CODE      VARCHAR2(2),
    RISK_LEVEL        VARCHAR2(10),
    SANCTIONED_REGIME VARCHAR2(3),
    LAST_REVIEW       DATE
);

-- Not a gs_ table: must not appear on the Format Templates page.
CREATE TABLE REF_COUNTRY (
    CODE VARCHAR2(2),
    NAME VARCHAR2(100)
);
`);

p("-- Certified versions");
for (const v of VERSIONS) {
    p(ins("VER_VERSION", ["VERSION_ID", "LIST_CODE", "LIST_NAME", "CONTENT_AS_OF", "STATUS", "OPERATOR_VISIBLE"],
        [v.id, q(v.code), q(v.name), d(v.asOf), q("CERTIFIED"), v.visible]));
}

let partyCount = 0;
for (const v of VERSIONS) {
    p("");
    p(`-- Version ${v.id}: ${v.name}${v.visible ? "" : " (hidden from operators)"}`);
    for (let i = 1; i <= PER_VERSION; i++) {
        const id = v.id * 1000000 + i;
        const name = i % 29 === 0 ? null : SPECIAL_NAMES[i] || NAMES[i % NAMES.length];
        const country = i % 41 === 0 ? null : COUNTRIES[i % COUNTRIES.length];
        const recordDate = `${1950 + (i % 50)}-${pad((i % 12) + 1)}-${pad((i % 27) + 1)}`;
        const flags = {
            ON_SANCTIONS: v.code === "SANCTIONS" || i % 2 === 0 ? 1 : 0,
            ON_WORLDCHECK: v.code === "WORLDCHECK" || i % 3 === 0 ? 1 : 0,
            ON_PFA: v.code === "PFA" || i % 5 === 0 ? 1 : 0
        };
        p(ins("VER_VERSION_MEMBER",
            ["VERSION_ID", "RECORD_ID", "BNP_ID", "NAME", "COUNTRY", "RECORD_DATE", "ACTION", "RISK_RATING", "BUSINESS_LINE", "REGION", "CHANGED_ON", "ON_SANCTIONS", "ON_WORLDCHECK", "ON_PFA"],
            [v.id, id, q("BNP" + id), q(name), q(country), d(recordDate), q(ACTIONS[i % 3]), q(RISKS[i % 3]), q(LINES[i % 4]), q(REGIONS[i % 5]),
                d(minusDays(v.asOf, i % 90)), flags.ON_SANCTIONS, flags.ON_WORLDCHECK, flags.ON_PFA]));
    }
}

p("");
p("-- Golden source: one party per record");
for (const v of VERSIONS) {
    for (let i = 1; i <= PER_VERSION; i++) {
        const id = v.id * 1000000 + i;
        partyCount++;
        p(ins("GS_PARTY", ["BNP_ID", "FULL_NAME", "PARTY_TYPE", "NATIONALITY", "BIRTH_PLACE", "RISK_SCORE"],
            [q("BNP" + id), q(SPECIAL_NAMES[i] || "Party " + id), q(PARTY_TYPES[i % 3]), q(COUNTRIES[i % 10]), q(CITIES[(i + 3) % 10]), (i * 37) % 100]));
    }
}

p("");
p("-- Golden source: addresses (every 13th record has none)");
for (const v of VERSIONS) {
    for (let i = 1; i <= PER_VERSION; i++) {
        if (i % 13 === 0) continue;
        const id = v.id * 1000000 + i;
        p(ins("GS_ADDRESS", ["BNP_ID", "STREET", "CITY", "POSTAL_CODE", "COUNTRY_CODE"],
            [q("BNP" + id), q(SPECIAL_STREETS[i] || (i % 200 + 1) + " " + STREETS[i % 5]), q(CITIES[i % 10]), q(String((i * 131) % 100000).padStart(5, "0")), q(COUNTRIES[i % 10])]));
    }
}

p("");
p("-- Golden source: identifiers (every 4th record has two)");
for (const v of VERSIONS) {
    for (let i = 1; i <= PER_VERSION; i++) {
        const id = v.id * 1000000 + i;
        p(ins("GS_IDENTIFIER", ["BNP_ID", "ID_TYPE", "ID_VALUE", "ISSUED_BY"], [q("BNP" + id), q(ID_TYPES[i % 3]), q("ID" + id), q(COUNTRIES[i % 10])]));
        if (i % 4 === 0) {
            p(ins("GS_IDENTIFIER", ["BNP_ID", "ID_TYPE", "ID_VALUE", "ISSUED_BY"], [q("BNP" + id), q(ID_TYPES[(i + 1) % 3]), q("AL" + id), q(COUNTRIES[(i + 1) % 10])]));
        }
    }
}

p("");
p("-- Golden source: sanction programmes");
for (const v of VERSIONS) {
    for (let i = 1; i <= PER_VERSION; i++) {
        const id = v.id * 1000000 + i;
        p(ins("GS_SANCTION_PROGRAM", ["BNP_ID", "PROGRAM_CODE", "LISTED_ON"],
            [q("BNP" + id), q(PROGRAMS[i % 4]), d(`${2015 + (i % 10)}-${pad((i % 12) + 1)}-${pad((i % 27) + 1)}`)]));
    }
}

p("");
p(ins("GS_LOAD_LOG", ["LOAD_REF", "LOADED_AT", "ROW_COUNT"], [q("LOAD-0001"), "TIMESTAMP '2026-11-18 06:00:00'", partyCount]));
p("");
p("-- Country risk: one row per BNP_ID");
for (const v of VERSIONS) {
    for (let i = 1; i <= PER_VERSION; i++) {
        const id = v.id * 1000000 + i;
        const c = i % 10;
        p(ins("GS_COUNTRY_RISK", ["BNP_ID", "COUNTRY_CODE", "RISK_LEVEL", "SANCTIONED_REGIME", "LAST_REVIEW"],
            [q("BNP" + id), q(COUNTRIES[c]), q(RISKS[c % 3]), q(c % 4 === 0 ? "YES" : "NO"), d(`2026-${pad(c % 12 + 1)}-15`)]));
    }
}
p(ins("REF_COUNTRY", ["CODE", "NAME"], [q("FR"), q("France")]));
p(ins("REF_COUNTRY", ["CODE", "NAME"], [q("GB"), q("United Kingdom")]));
p("");
p("COMMIT;");

fs.writeFileSync(out, L.join("\n") + "\n");
console.log("wrote", out, L.length, "lines");
