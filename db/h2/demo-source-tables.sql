-- H2 demo only: the REGLISS-owned certified version catalog the module reads. On PostgreSQL it already
-- exists (db/postgres/regliss-mock.sql, or the real REGLISS schema). Seeded with demo versions at start-up.
CREATE TABLE IF NOT EXISTS ver_version (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id       bigint NOT NULL UNIQUE,
    list_code        varchar(255) NOT NULL,
    list_name        varchar(255) NOT NULL,
    content_as_of    date,
    status           varchar(255) NOT NULL,
    operator_visible boolean DEFAULT TRUE NOT NULL
);
