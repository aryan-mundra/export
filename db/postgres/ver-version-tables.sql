-- REGLISS list-version tables, created EMPTY: ver_version and ver_version_member.
--
-- Normally these come from the REGLISS dump (they are read-only source tables: the module reads them and never
-- writes them). Run this only when the dump you loaded does not contain them (for example a Dow Jones dump that
-- brings only gs_ / cfg_dj_ tables), so the module starts. With empty tables there is no version to export until
-- REGLISS data is loaded into them.
--
-- How: in pgAdmin, Query Tool on your database -> Open File -> this file -> F5.
--      or: psql -U postgres -d reglissData -f db/postgres/ver-version-tables.sql
-- Safe to run again: nothing is dropped, existing tables are left as they are.

CREATE TABLE IF NOT EXISTS public.ver_version (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id       BIGINT       NOT NULL,
    list_code        VARCHAR(255) NOT NULL,
    list_name        VARCHAR(255) NOT NULL,
    content_as_of    DATE,
    status           VARCHAR(255) NOT NULL,
    operator_visible BOOLEAN      DEFAULT TRUE NOT NULL,
    CONSTRAINT uq_ver_version_version_id UNIQUE (version_id)
);

CREATE TABLE IF NOT EXISTS public.ver_version_member (
    version_id    BIGINT      NOT NULL,
    record_id     BIGINT      NOT NULL,
    bnp_id        VARCHAR(20) NOT NULL,
    name          VARCHAR(200),
    country       VARCHAR(2),
    record_date   DATE,
    action        VARCHAR(10),
    risk_rating   VARCHAR(10),
    business_line VARCHAR(50),
    region        VARCHAR(50),
    changed_on    DATE,
    on_sanctions  SMALLINT DEFAULT 0 NOT NULL,
    on_worldcheck SMALLINT DEFAULT 0 NOT NULL,
    on_pfa        SMALLINT DEFAULT 0 NOT NULL,
    CONSTRAINT pk_ver_version_member PRIMARY KEY (version_id, record_id)
);
