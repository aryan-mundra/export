-- =============================================================================
-- REGLISS Export module: the tables the module WRITES. All are named ver_export_*.
--
-- The module never creates or alters tables itself on PostgreSQL (spring.jpa.hibernate.ddl-auto=none).
-- This script is the schema: run it once per database, or let the application run it at start-up
-- (spring.sql.init, on by default; REGLISS_SCHEMA_INIT=never turns it off when a DBA owns the schema).
-- It is safe to run again: every statement is CREATE ... IF NOT EXISTS.
--
-- Read-only source tables (owned by REGLISS, never written): ver_version, ver_version_member, gs_*.
-- SchemaScriptTest checks this script against the application's entities.
-- =============================================================================

-- ---------------------------------------------------------------- users and configuration

-- Users who can sign in (role MAKER or APPROVER).
CREATE TABLE IF NOT EXISTS ver_export_user (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      varchar(255) NOT NULL UNIQUE,
    display_name  varchar(255) NOT NULL,
    password_hash varchar(255) NOT NULL,
    role          varchar(255) NOT NULL
);

-- Who receives files, in which format and scope, through which endpoint, with which template.
CREATE TABLE IF NOT EXISTS ver_export_subscriber (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                   varchar(255) NOT NULL UNIQUE,
    format_type            varchar(255) NOT NULL,
    scope                  varchar(255) NOT NULL,
    export_mode            varchar(255) NOT NULL,
    business_line          varchar(255),
    region                 varchar(255),
    cft_endpoint           varchar(255),
    endpoint_status        varchar(255),
    template_family_id     bigint,
    active                 boolean NOT NULL,
    max_batch_size         integer NOT NULL,
    export_timeout_minutes integer NOT NULL,
    created_at             timestamp(6),
    updated_at             timestamp(6)
);
CREATE INDEX IF NOT EXISTS ix_ver_export_subscriber_template ON ver_export_subscriber (template_family_id);

-- One row per version of a template. Versions of one template share family_id; one is active (in use).
CREATE TABLE IF NOT EXISTS ver_export_template (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    family_id        bigint,
    name             varchar(255) NOT NULL,
    version_number   integer NOT NULL,
    active           boolean NOT NULL,
    status           varchar(255) NOT NULL,             -- PENDING, APPROVED, CHANGES_REQUESTED, REJECTED, SUPERSEDED
    created_by       varchar(255) NOT NULL,
    created_by_name  varchar(255) NOT NULL,
    created_at       timestamp(6),
    approved_by      varchar(255),
    approved_by_name varchar(255),
    approved_at      timestamp(6),
    reviewed_by      varchar(255),
    reviewed_by_name varchar(255),
    reviewed_at      timestamp(6),
    review_comment   varchar(2000)
);
CREATE INDEX IF NOT EXISTS ix_ver_export_template_family ON ver_export_template (family_id, version_number);

-- Columns of a template version: gs_ table and column, name in the file, order.
CREATE TABLE IF NOT EXISTS ver_export_template_field (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_id   bigint NOT NULL REFERENCES ver_export_template (id),
    source_table  varchar(255),
    source_column varchar(255) NOT NULL,
    header_name   varchar(255) NOT NULL,
    join_column   varchar(255),
    join_field    varchar(255),
    position      integer NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_ver_export_template_field_template ON ver_export_template_field (template_id, position);

-- Row filters of a template version; all must pass.
CREATE TABLE IF NOT EXISTS ver_export_template_filter (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_id   bigint NOT NULL REFERENCES ver_export_template (id),
    source_table  varchar(255) NOT NULL,
    source_column varchar(255) NOT NULL,
    filter_op     varchar(20) NOT NULL,                 -- in, not_in, contains, eq, ne, gt, gte, lt, lte, between, empty, not_empty
    filter_values text,                                 -- JSON array of strings
    include_blank boolean NOT NULL,
    position      integer NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_ver_export_template_filter_template ON ver_export_template_filter (template_id, position);

-- ---------------------------------------------------------------- data versions (snapshots)

-- One row per template and list: the catalog row screens list, and the row locked while a version is numbered.
CREATE TABLE IF NOT EXISTS ver_export_snapshot_series (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    family_id          bigint NOT NULL,
    list_code          varchar(255) NOT NULL,
    template_name      varchar(255),
    list_name          varchar(255),
    version_count      integer,
    latest_snapshot_id bigint,
    latest_label       varchar(255),
    latest_at          timestamp(6),
    exports_served     bigint,
    total_rows         bigint,
    stored_rows        bigint,
    last_used_at       timestamp(6),
    CONSTRAINT uq_snapshot_series UNIQUE (family_id, list_code)
);
CREATE INDEX IF NOT EXISTS ix_snapshot_series_used ON ver_export_snapshot_series (last_used_at);
CREATE INDEX IF NOT EXISTS ix_snapshot_series_name ON ver_export_snapshot_series (template_name, list_name);

-- One row per data version (1.1, 1.2, ...). Never updated except its usage counters; never deleted.
-- Its rows are in a table of its own, named in table_name (ver_<list>_v<major>_<minor>), which the
-- application creates when the version is made. See docs/ver-export-tables.md.
CREATE TABLE IF NOT EXISTS ver_export_snapshot (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    family_id            bigint NOT NULL,
    list_code            varchar(255) NOT NULL,
    list_name            varchar(255),
    template_id          bigint NOT NULL REFERENCES ver_export_template (id),
    template_name        varchar(255),
    version_major        integer NOT NULL,
    version_minor        integer NOT NULL,
    label                varchar(255) NOT NULL,
    table_name           varchar(63) NOT NULL,          -- e.g. ver_list_apac_v1_1
    source_version_id    bigint,
    fingerprint          varchar(64) NOT NULL,          -- SHA-256 of the column layout and every row, in order
    row_count            bigint NOT NULL,
    stored_rows          bigint NOT NULL,               -- rows copied into its table
    columns_json         text,
    previous_snapshot_id bigint,
    previous_label       varchar(255),
    inserted_rows        bigint,
    deleted_rows         bigint,
    changed_rows         bigint,
    created_at           timestamp(6),
    created_by           varchar(255),
    created_by_name      varchar(255),
    created_job_id       bigint,
    reuse_count          integer NOT NULL,
    last_used_at         timestamp(6),
    CONSTRAINT uq_snapshot_number UNIQUE (family_id, list_code, version_major, version_minor),
    CONSTRAINT uq_snapshot_dataset UNIQUE (family_id, list_code, template_id, fingerprint),
    CONSTRAINT uq_snapshot_table UNIQUE (table_name)
);
CREATE INDEX IF NOT EXISTS ix_snapshot_series ON ver_export_snapshot (family_id, list_code);

-- ---------------------------------------------------------------- export runs

-- One row per run: an export of current data, or a send of a stored data version (mode RESEND).
CREATE TABLE IF NOT EXISTS ver_export_job (
    id                        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id                bigint NOT NULL,          -- certified list version (ver_version.version_id)
    list_code                 varchar(255),
    list_name                 varchar(255),
    from_date                 date,
    to_date                   date,
    mode                      varchar(255),             -- EXPORT or RESEND
    snapshot_id               bigint,
    snapshot_label            varchar(255),
    snapshot_template         varchar(255),
    format_override           varchar(255),             -- RESEND: one format for every file, or null
    subscriber_ids            text,                     -- the subscribers it was limited to ("id" or "id:FORMAT"), or null for all
    format_template_id        bigint,
    format_template_version   integer,
    triggered_by              varchar(255),
    status                    varchar(255) NOT NULL,    -- PENDING, IN_PROGRESS, COMPLETED, HELD, FAILED
    total_subscribers         integer NOT NULL,
    completed_subscribers     integer NOT NULL,
    failed_subscribers        integer NOT NULL,
    held_subscribers          integer NOT NULL,
    skipped_subscribers       integer NOT NULL,
    total_records_processed   bigint NOT NULL,
    total_records_quarantined bigint NOT NULL,
    error_message             varchar(4000),
    started_at                timestamp(6),
    completed_at              timestamp(6),
    created_at                timestamp(6)
);
CREATE INDEX IF NOT EXISTS ix_ver_export_job_created ON ver_export_job (created_at);
CREATE INDEX IF NOT EXISTS ix_ver_export_job_status ON ver_export_job (status);
CREATE INDEX IF NOT EXISTS ix_ver_export_job_list ON ver_export_job (list_code, created_at);

-- One row per subscriber within a run: status, counts, file, and the data version it was built from.
CREATE TABLE IF NOT EXISTS ver_export_job_subscriber (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    export_job_id           bigint REFERENCES ver_export_job (id),
    subscriber_id           bigint,
    subscriber_name         varchar(255),
    format_type             varchar(255),
    status                  varchar(255) NOT NULL,      -- PENDING, IN_PROGRESS, COMPLETED, HELD, FAILED, SKIPPED
    records_processed       integer NOT NULL,
    records_quarantined     integer NOT NULL,
    file_size_bytes         bigint NOT NULL,
    file_path               varchar(1000),
    archive_path            varchar(1000),
    error_message           varchar(4000),
    hold_reason             varchar(1000),
    retry_count             integer NOT NULL,
    format_template_id      bigint,
    format_template_version integer,
    snapshot_id             bigint,
    snapshot_label          varchar(255),
    snapshot_outcome        varchar(255),               -- CREATED, REUSED or RESENT
    accepted_by             varchar(255),
    accepted_at             timestamp(6),
    started_at              timestamp(6),
    completed_at            timestamp(6),
    created_at              timestamp(6)
);
CREATE INDEX IF NOT EXISTS ix_ver_export_job_subscriber_job ON ver_export_job_subscriber (export_job_id);
CREATE INDEX IF NOT EXISTS ix_ver_export_job_subscriber_snapshot ON ver_export_job_subscriber (snapshot_id);
CREATE INDEX IF NOT EXISTS ix_ver_export_job_subscriber_status ON ver_export_job_subscriber (status);

-- Every file built: where it is, its SHA-256, template version, and BUILDING / BUILT / SENT / FAILED.
CREATE TABLE IF NOT EXISTS ver_export_file (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    export_job_id           bigint NOT NULL REFERENCES ver_export_job (id),
    job_subscriber_id       bigint NOT NULL REFERENCES ver_export_job_subscriber (id),
    subscriber_id           bigint NOT NULL,
    version_id              bigint NOT NULL,
    export_mode             varchar(255),
    format_type             varchar(255) NOT NULL,
    format_template_id      bigint,
    format_template_version integer,
    file_name               varchar(255) NOT NULL,
    file_path               varchar(1000) NOT NULL,
    file_size               bigint NOT NULL,
    file_hash               varchar(64),
    record_count            integer NOT NULL,
    status                  varchar(255) NOT NULL,
    archive_path            varchar(1000),
    created_by              varchar(255),
    created_at              timestamp(6),
    sent_at                 timestamp(6)
);
CREATE INDEX IF NOT EXISTS ix_ver_export_file_job ON ver_export_file (export_job_id);
CREATE INDEX IF NOT EXISTS ix_ver_export_file_subscriber ON ver_export_file (subscriber_id);

-- Every list entry in every file, with its line: "did subscriber X get record Y, and in which file?"
CREATE TABLE IF NOT EXISTS ver_export_file_record (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_id     bigint NOT NULL REFERENCES ver_export_file (id),
    record_id   varchar(255) NOT NULL,
    action      varchar(255),
    line_number integer NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_ver_export_file_record_file ON ver_export_file_record (file_id);
CREATE INDEX IF NOT EXISTS ix_ver_export_file_record_record ON ver_export_file_record (record_id);

-- Every delivery attempt over CFT.
CREATE TABLE IF NOT EXISTS ver_export_delivery (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscriber_id           bigint,
    version_id              bigint,
    export_type             varchar(255),
    format_type             varchar(255),
    format_template_id      bigint,
    format_template_version integer,
    record_count            integer NOT NULL,
    status                  varchar(255) NOT NULL,
    cft_tracking_id         varchar(255),
    file_path               varchar(1000),
    archive_path            varchar(1000),
    file_hash               varchar(255),
    quarantine_note         varchar(1000),
    error_message           varchar(4000),
    delivered_at            timestamp(6),
    created_at              timestamp(6)
);
CREATE INDEX IF NOT EXISTS ix_ver_export_delivery_subscriber ON ver_export_delivery (subscriber_id, created_at);
CREATE INDEX IF NOT EXISTS ix_ver_export_delivery_file ON ver_export_delivery (file_path);

-- Records held back from a file, with the reason and who accepted the omission.
CREATE TABLE IF NOT EXISTS ver_export_quarantine (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    export_job_id        bigint,
    subscriber_status_id bigint REFERENCES ver_export_job_subscriber (id),
    subscriber_id        bigint,
    version_id           bigint,
    record_identifier    varchar(255),
    target_table         varchar(255),
    quarantine_reason    varchar(4000) NOT NULL,
    patch_applied        boolean NOT NULL,
    accepted_by          varchar(255),
    accepted_at          timestamp(6),
    created_at           timestamp(6)
);
CREATE INDEX IF NOT EXISTS ix_ver_export_quarantine_status ON ver_export_quarantine (subscriber_status_id, patch_applied);

-- ---------------------------------------------------------------- audit

-- Every change, with who made it. Only ever added to.
CREATE TABLE IF NOT EXISTS ver_export_audit (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type   varchar(255) NOT NULL,                -- EXPORT_JOB, SUBSCRIBER, TEMPLATE, DATA_VERSION
    entity_id     bigint,
    export_job_id bigint,
    subscriber_id bigint,
    action        varchar(255) NOT NULL,
    details       varchar(4000),
    actor         varchar(255) NOT NULL,
    logged_at     timestamp(6)
);
CREATE INDEX IF NOT EXISTS ix_ver_export_audit_job ON ver_export_audit (export_job_id, logged_at);
CREATE INDEX IF NOT EXISTS ix_ver_export_audit_entity ON ver_export_audit (entity_type, entity_id);

-- Dumps imported from db/dumps at start-up (written by the importer, before the application connects).
CREATE TABLE IF NOT EXISTS ver_export_dump_import (
    sha256      varchar(64) PRIMARY KEY,
    file_name   varchar(500) NOT NULL,
    file_size   bigint,
    errors      integer,
    imported_at timestamp DEFAULT now()
);
